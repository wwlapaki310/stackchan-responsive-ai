# Writes firmware/answer_demo/secrets.h from local environment variables. The output is
# git-ignored (secrets.*). Never commit it and never paste its content into logs.
#   SARASHINA_API_KEY        API key (required)
#   STACKCHAN_WIFI_SSID      2.4 GHz network name (required for network use)
#   STACKCHAN_WIFI_PASS      password (empty for an open network)
param([string]$Out = (Join-Path $PSScriptRoot '..\firmware\answer_demo\secrets.h'))

function Get-Setting([string]$name) {
  foreach ($scope in 'Process', 'User', 'Machine') {
    $v = [Environment]::GetEnvironmentVariable($name, $scope)
    if ($v) { return $v }
  }
  return ''
}
function Escape-C([string]$s) { return $s.Replace('\', '\\').Replace('"', '\"') }

$key = Get-Setting 'SARASHINA_API_KEY'
$ssid = Get-Setting 'STACKCHAN_WIFI_SSID'
$pass = Get-Setting 'STACKCHAN_WIFI_PASS'
if (-not $key) { Write-Warning 'SARASHINA_API_KEY is not set; the device will report a missing key.' }
if (-not $ssid) { Write-Warning 'STACKCHAN_WIFI_SSID is not set; the device will stay offline.' }

$text = "// Generated by tools/gen_secrets.ps1. Git-ignored. Do not commit.`r`n#pragma once`r`n" +
  "#define SARASHINA_API_KEY `"$(Escape-C $key)`"`r`n" +
  "#define WIFI_SSID `"$(Escape-C $ssid)`"`r`n" +
  "#define WIFI_PASS `"$(Escape-C $pass)`"`r`n"
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[IO.File]::WriteAllText($Out, $text)
Write-Output ("wrote {0} (api_key_set={1} ssid_set={2} pass_set={3})" -f (Resolve-Path $Out), [bool]$key, [bool]$ssid, [bool]$pass)
