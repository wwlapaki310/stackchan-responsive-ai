#!/usr/bin/env python3
"""Pack mono 16-bit 16 kHz WAV files into a C header (used by tools/gen_voice.ps1).

Usage: voice_pack.py <wav-dir> <comma-separated-names> <out.h> <voice-name>
Trims leading/trailing silence (keeps 60 ms) and normalises the peak to 85 percent.
Needs numpy.
"""
import sys
import wave
from pathlib import Path

import numpy as np

wav_dir, names, out, voice = Path(sys.argv[1]), sys.argv[2].split(","), Path(sys.argv[3]), sys.argv[4]
RATE = 16000
PAD = int(0.06 * RATE)
clips = []
for name in names:
    with wave.open(str(wav_dir / f"{name}.wav"), "rb") as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2 and w.getframerate() == RATE, name
        pcm = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.int32)
    loud = np.flatnonzero(np.abs(pcm) > 300)
    if loud.size:
        pcm = pcm[max(0, loud[0] - PAD): loud[-1] + PAD]
    peak = max(1, int(np.abs(pcm).max()))
    pcm = np.clip(pcm * (0.85 * 32767 / peak), -32768, 32767).astype(np.int16)
    clips.append((name, pcm))

lines = [
    f"// Generated by tools/gen_voice.ps1 (voice: {voice}). Git-ignored; do not commit.",
    "#pragma once",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "#define VOICE_CLIPS_AVAILABLE 1",
    f"#define VOICE_SAMPLE_RATE {RATE}",
    "struct VoiceClip { const int16_t* data; size_t samples; };",
]
for name, pcm in clips:
    body = ",".join(str(int(v)) for v in pcm)
    lines.append(f"static const int16_t kVoice_{name}[] = {{{body}}};")
lines.append("enum VoiceId { " + ", ".join(f"VOICE_{n.upper()}" for n, _ in clips) + ", VOICE_COUNT };")
lines.append("static const VoiceClip kVoiceClips[VOICE_COUNT] = {")
for name, pcm in clips:
    lines.append(f"  {{kVoice_{name}, {len(pcm)}}},")
lines.append("};")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
total = sum(len(p) for _, p in clips)
print(f"wrote {out} ({len(clips)} clips, {total * 2 // 1024} KiB, {total / RATE:.1f} s)")
for name, pcm in clips:
    print(f"  {name}: {len(pcm) / RATE:.2f} s")
